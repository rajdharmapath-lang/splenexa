export function getBatchYears(currentYear = new Date().getFullYear()) {
  const firstBatchYear = 2016;
  return Array.from(
    { length: Math.max(0, currentYear - firstBatchYear + 1) },
    (_, index) => String(firstBatchYear + index),
  );
}
